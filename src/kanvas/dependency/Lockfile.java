package kanvas.dependency;

import kanvas.project.Dependency;
import kanvas.project.KanvasProjectException;
import kanvas.project.TOMLParser;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;

record Lockfile(String inputs, List<Entry> entries) {
    static final int VERSION = 1;

    record Entry(Dependency.Maven coordinate, String classifier, String platform, String repository, String sha256) {}

    static Lockfile read(Path file) throws DependencyException {
        if (!Files.isRegularFile(file)) return null;
        try {
            Map<String, Object> toml = TOMLParser.parse(Files.readString(file, StandardCharsets.UTF_8), file.toString());
            if (!(toml.get("lockVersion") instanceof Long version) || version != VERSION)
                throw new DependencyException(file + " was written by a different version of Kanvas. Delete it and build again to recreate it.");
            List<Entry> entries = new ArrayList<>();
            if (toml.get("artifact") instanceof List<?> artifacts)
                for (Object artifact : artifacts) entries.add(entry((Map<?, ?>) artifact, file));
            return new Lockfile(string(toml, "inputs", file), entries);
        } catch (IOException | KanvasProjectException | ClassCastException e) {
            throw new DependencyException(file + " is damaged (" + e.getMessage() + "). Delete it and build again to recreate it.", e);
        }
    }

    private static Entry entry(Map<?, ?> artifact, Path file) throws DependencyException {
        String[] coordinate = string(artifact, "coordinate", file).split(":");
        Dependency.Scope scope = Dependency.Scope.parse(string(artifact, "scope", file));
        if (coordinate.length != 3 || scope == null || Dependency.Maven.problem(coordinate[0], coordinate[1], coordinate[2]) != null)
            throw new DependencyException(file + " has an invalid entry: " + artifact);
        String classifier = (String) artifact.get("classifier");
        if (classifier != null && !Dependency.Maven.CLASSIFIER.matcher(classifier).matches())
            throw new DependencyException(file + " has an invalid classifier: " + classifier);
        return new Entry(new Dependency.Maven(coordinate[0], coordinate[1], coordinate[2], scope), classifier,
            (String) artifact.get("platform"), string(artifact, "repository", file), string(artifact, "sha256", file));
    }

    private static String string(Map<?, ?> table, String key, Path file) throws DependencyException {
        if (table.get(key) instanceof String value) return value;
        throw new DependencyException(file + " is missing '" + key + "'. Delete it and build again to recreate it.");
    }

    String write() {
        StringBuilder toml = new StringBuilder("# Generated by Kanvas. Commit this file; don't edit it by hand.\n")
            .append("lockVersion = ").append(VERSION).append('\n')
            .append("inputs = \"").append(inputs).append("\"\n");
        for (Entry entry : entries) {
            toml.append("\n[[artifact]]\ncoordinate = \"").append(entry.coordinate().coordinate()).append("\"\n");
            if (entry.classifier() != null) toml.append("classifier = \"").append(entry.classifier()).append("\"\n");
            if (entry.platform() != null) toml.append("platform = \"").append(entry.platform()).append("\"\n");
            toml.append("scope = \"").append(entry.coordinate().scope().label()).append("\"\n")
                .append("repository = \"").append(entry.repository().replace("\\", "\\\\").replace("\"", "\\\"")).append("\"\n")
                .append("sha256 = \"").append(entry.sha256()).append("\"\n");
        }
        return toml.toString();
    }
}
